package reto1;

public class Funciones3 {
	public static int multiplicar(int n1, int n2) {
		int multi = n1*n2;
		return multi;
	}
	public static int dividir(int n1,int n2){
		int dividir = n1/n2;
		return dividir;
	}
	public static boolean positivo(int n1) {
		if (n1>=0) { 
			return true;
		}else {
			return false;
		}
	}

}
